#!/usr/bin/env python3
"""Audio license manifest: every music/SFX file used in a render must be registered here.

assets/audio/manifest.json:
  {"files": {"assets/audio/sfx/chain_clink.mp3": {
      "name": "chain_clink", "kind": "sfx", "source": "freesound",
      "url": "https://freesound.org/s/12345/", "author": "someone",
      "license": "CC0", "attribution": null}}}

Paths are relative to the repo root. The orchestrator refuses unregistered audio files and audio
whose license isn't on the allow-list below, so nothing with unclear rights ends up in a
monetized video by accident. Attribution lines are collected into the video's credits file.

  python scripts/audio_manifest.py add assets/audio/music/tension.mp3 --name tension_drone --kind music \\
      --source youtube_audio_library --author "Artist Name" --license "YouTube Audio Library" \\
      --attribution "Music: Track Name by Artist Name"
  python scripts/audio_manifest.py list
  python scripts/audio_manifest.py check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from pipeline_utils import ASSETS_DIR, PROJECT_ROOT, PipelineError, get_logger, load_json, save_json, setup_logging

log = get_logger("audiolic")

MANIFEST_PATH = ASSETS_DIR / "audio" / "manifest.json"
# Licenses that are safe on a monetized channel. Deliberately excluded:
#   *-NC (non-commercial), *-ND (no derivatives; a video edit IS a derivative), *-SA (share-alike would
#   force the whole video under the same license), and anything unknown.
ALLOWED_LICENSES = {
    "CC0": "public domain dedication; no attribution needed",
    "YouTube Audio Library": "free for YouTube videos; some tracks require an attribution line",
    "CC-BY-3.0": "attribution required",
    "CC-BY-4.0": "attribution required",
    "own": "you made it yourself",
    "generated": "generated by this project's own tools",
}
NEEDS_ATTRIBUTION = {"CC-BY-3.0", "CC-BY-4.0"}
KINDS = ("music", "sfx", "ambience", "bgm")


def load_manifest() -> dict:
    if not MANIFEST_PATH.is_file():
        return {"files": {}}
    data = load_json(MANIFEST_PATH)
    data.setdefault("files", {})
    return data


def save_manifest(data: dict) -> Path:
    data["files"] = dict(sorted(data["files"].items()))
    return save_json(MANIFEST_PATH, data)


def rel_key(path: Path) -> str:
    path = Path(path).resolve()
    try:
        return path.relative_to(PROJECT_ROOT).as_posix()
    except ValueError:
        raise PipelineError(f"Audio file {path} is outside the project folder; copy it into assets/audio/ first.")


def check_entry(key: str, entry: dict) -> None:
    lic = entry.get("license")
    if lic not in ALLOWED_LICENSES:
        raise PipelineError(f"{key}: license '{lic}' is not allowed for monetized videos. Allowed: "
                            + ", ".join(ALLOWED_LICENSES))
    if lic in NEEDS_ATTRIBUTION and not (entry.get("attribution") or "").strip():
        raise PipelineError(f"{key}: license {lic} requires an attribution line (--attribution).")
    if entry.get("source") == "youtube_audio_library" and entry.get("attribution") is None:
        log.warning("%s: YouTube Audio Library tracks sometimes require attribution; if the library page "
                    "shows a 'copy attribution' text, add it with --attribution.", key)


def entry_for(path: Path, manifest: dict | None = None) -> dict:
    """Manifest entry for an audio file; raises if unregistered or not allowed."""
    manifest = manifest or load_manifest()
    key = rel_key(path)
    entry = manifest["files"].get(key)
    if entry is None:
        raise PipelineError(f"Audio file '{key}' is not in {MANIFEST_PATH.relative_to(PROJECT_ROOT)}. Register it "
                            "with: python scripts/audio_manifest.py add <file> --name ... --license ...")
    check_entry(key, entry)
    return entry


def path_for_name(name: str, manifest: dict | None = None) -> Path | None:
    manifest = manifest or load_manifest()
    for key, entry in manifest["files"].items():
        if entry.get("name") == name:
            return PROJECT_ROOT / key
    return None


def credit_lines(paths: list[Path], manifest: dict | None = None) -> list[str]:
    manifest = manifest or load_manifest()
    lines = []
    for p in sorted({Path(p).resolve() for p in paths}):
        entry = entry_for(p, manifest)
        if entry.get("attribution"):
            lines.append(entry["attribution"])
        elif entry["license"] == "CC0" and entry.get("author"):
            lines.append(f"{entry.get('name', p.stem)}: {entry['author']} via {entry.get('source', '?')} (CC0)")
    return list(dict.fromkeys(lines))


def add(path: Path, name: str, kind: str, source: str, license_: str, author: str | None, url: str | None,
        attribution: str | None, force: bool = False) -> str:
    if not Path(path).is_file():
        raise PipelineError(f"File not found: {path}")
    if kind not in KINDS:
        raise PipelineError(f"--kind must be one of {', '.join(KINDS)}")
    manifest = load_manifest()
    key = rel_key(path)
    clash = [k for k, e in manifest["files"].items() if e.get("name") == name and k != key]
    if clash:
        raise PipelineError(f"Name '{name}' is already used by {clash[0]}.")
    if key in manifest["files"] and not force:
        raise PipelineError(f"{key} is already registered (use --force to replace).")
    entry = {"name": name, "kind": kind, "source": source, "url": url, "author": author,
             "license": license_, "attribution": attribution}
    check_entry(key, entry)
    manifest["files"][key] = entry
    save_manifest(manifest)
    return key


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Register and check licensed audio files.")
    sub = p.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("add", help="Register an audio file.")
    a.add_argument("file", type=Path)
    a.add_argument("--name", required=True, help="Short id used in scripts, e.g. tension_drone")
    a.add_argument("--kind", required=True, choices=KINDS)
    a.add_argument("--source", required=True, help="youtube_audio_library | freesound | own | generated | ...")
    a.add_argument("--license", required=True, choices=list(ALLOWED_LICENSES))
    a.add_argument("--author")
    a.add_argument("--url")
    a.add_argument("--attribution", help="Exact credit line, if the license/source asks for one.")
    a.add_argument("--force", action="store_true")
    sub.add_parser("list", help="Show registered audio.")
    sub.add_parser("check", help="Verify every registered file exists and is allowed.")
    args = p.parse_args(argv)
    setup_logging()
    try:
        if args.cmd == "add":
            key = add(args.file, args.name, args.kind, args.source, args.license, args.author, args.url,
                      args.attribution, args.force)
            print(f"registered {key}")
        elif args.cmd == "list":
            for key, e in load_manifest()["files"].items():
                print(f"{e.get('name', '?'):<18} {e.get('kind', '?'):<8} {e['license']:<22} {key}")
        else:
            bad = 0
            for key, e in load_manifest()["files"].items():
                try:
                    check_entry(key, e)
                    if not (PROJECT_ROOT / key).is_file():
                        raise PipelineError(f"{key}: file is missing on disk")
                    print(f"OK      {key}")
                except PipelineError as exc:
                    bad += 1
                    print(f"PROBLEM {exc}")
            return 1 if bad else 0
        return 0
    except PipelineError as exc:
        log.error("%s", exc)
        return 1


if __name__ == "__main__":
    sys.exit(main())
